    private void btnDangKyNgayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDangKyNgayActionPerformed
        try {
        String TenTaiKhoan = txtTenTaiKhoan.getText();
        String MatKhau = txtMatKhau.getText();
        String Email = txtEmail.getText();
        if(TenTaiKhoan.isEmpty() || MatKhau.isEmpty() || Email.isEmpty()){
            JOptionPane.showMessageDialog(this, "Nhập đầy đủ thông tin");
            return;
        }
        Connection conn = KetNoiDB.getConnection();
        String sql = "INSERT INTO TaiKhoan (TenTaiKhoan, MatKhau , Email) VALUES (?,?,?)";
        PreparedStatement st = conn.prepareStatement(sql);
        st.setString(1, TenTaiKhoan);
        st.setString(2, MatKhau);
        st.setString(3, Email);
        int TinhTrangDangKy = st.executeUpdate();
        if(TinhTrangDangKy > 0){
            JOptionPane.showMessageDialog(this, "Đăng Ký Thành Công!");
        }else{
            JOptionPane.showMessageDialog(this, "Đăng Ký Thất Bại");
        }
        st.close();
        conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi:" + e.getMessage());
        }
    }//GEN-LAST:event_btnDangKyNgayActionPerformed

