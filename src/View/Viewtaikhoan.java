    private void thongBao(String s, boolean thanhCong) {
        lblKetQua.setForeground(thanhCong
                ? new java.awt.Color(0x2E, 0x7D, 0x32)
                : new java.awt.Color(0xD3, 0x2F, 0x2F));
        lblKetQua.setText(s);
    }

    private void doiMatKhau() {
        String cu  = new String(pwCu.getPassword());
        String moi = new String(pwMoi.getPassword());
        String lai = new String(pwLai.getPassword());

        if (cu.isEmpty() || moi.isEmpty() || lai.isEmpty()) {
            thongBao("Hãy nhập đủ ba ô mật khẩu", false);
            return;
        }
        if (moi.length() < 6) {
            thongBao("Mật khẩu mới phải có ít nhất 6 ký tự", false);
            return;
        }
        if (!moi.equals(lai)) {
            thongBao("Hai mật khẩu mới không khớp", false);
            return;
        }
        if (moi.equals(cu)) {
            thongBao("Mật khẩu mới phải khác mật khẩu cũ", false);
            return;
        }
        try {
            if (TaiKhoanDAO.doiMatKhau(PhienDangNhap.tenDangNhap, cu, moi)) {
                napThongTin();                       // xóa các ô nhập
                thongBao("Đổi mật khẩu thành công!", true);
            } else {
                thongBao("Mật khẩu cũ không đúng", false);
            }
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            thongBao("Lỗi CSDL: " + ex.getMessage(), false);
        }
    }

